CREATE TABLE IF NOT EXISTS user_dtls (
  id INT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS specialist (
  id INT AUTO_INCREMENT PRIMARY KEY,
  spec_name VARCHAR(120) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS doctor (
  id INT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  dob VARCHAR(10) NOT NULL,
  qualification VARCHAR(160) NOT NULL,
  specialist VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  mobno VARCHAR(20) NOT NULL,
  password VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS appointment (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  fullname VARCHAR(120) NOT NULL,
  gender VARCHAR(30) NOT NULL,
  age VARCHAR(3) NOT NULL,
  appoint_date DATE NOT NULL,
  email VARCHAR(254) NOT NULL,
  phno VARCHAR(20) NOT NULL,
  diseases VARCHAR(500) NOT NULL,
  doctor_id INT NOT NULL,
  address VARCHAR(500) NOT NULL,
  status VARCHAR(1000) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES user_dtls(id),
  FOREIGN KEY (doctor_id) REFERENCES doctor(id)
);
